const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1280,height:720}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5173/#/upload');
 const select=page.getByLabel('来源机位');
 await select.waitFor({state:'attached'});
 await page.locator('details.form-block summary').click();
 await select.scrollIntoViewIfNeeded();await page.waitForTimeout(600);
 const style=await select.evaluate(e=>({font:getComputedStyle(e).fontSize,height:e.offsetHeight,border:getComputedStyle(e).borderTopWidth,appearance:getComputedStyle(e).appearance}));
 assert.deepEqual(style,{font:'12px',height:36,border:'1px',appearance:'none'});
 assert.equal(await select.inputValue(),'');
 await page.screenshot({path:'data/ui-source-after.png'});
 await page.locator('details.form-block summary').focus();await page.keyboard.press('Tab');
 assert.equal(await select.evaluate(e=>e===document.activeElement),true);
 assert.equal(await select.evaluate(e=>getComputedStyle(e).outlineStyle),'solid');
 await page.screenshot({path:'data/ui-source-focus.png'});
 await select.selectOption('CAM-MOMOYO-REAL-TABLE');
 await page.screenshot({path:'data/ui-source-selected.png'});
 // Browser-only visual fixture; no upload or model request occurs.
 await select.evaluate(e=>{e.disabled=true});
 assert.equal(await select.isDisabled(),true);
 await page.screenshot({path:'data/ui-source-disabled.png'});
 await page.setViewportSize({width:1440,height:900});await page.reload();
 await page.locator('details.form-block summary').click();await page.waitForTimeout(600);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'data/ui-source-wide.png'});
 await page.setViewportSize({width:1280,height:720});
 await page.goto('http://127.0.0.1:5173/#/run/RUN-1AA5F1490CD8');
 await page.getByText('无确认事件',{exact:true}).waitFor();await page.waitForTimeout(600);
 await page.screenshot({path:'data/ui-run-reviewed-top.png'});
 await page.locator('main.page-shell').evaluate(e=>{e.scrollTop=e.scrollHeight});
 await page.waitForTimeout(200);
 await page.screenshot({path:'data/ui-run-reviewed-cost.png'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log('Source UI audit passed: expanded/default/selected/disabled/keyboard focus; 1280 and 1440; run detail; computed style',style);
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
